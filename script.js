const MainArticle = ({ title, image, category, description, source }) => (
  <article className="main-article"> 
    <div className="main-article__image-container"> 
      <img className="article-img main-article__img" src={image} alt="Фото новости" /> 
    </div> 
    <div className="main-article__content"> 
      <span className="article-category">{category}</span> 
      <h2 className="main-article__title">{title}</h2> 
      <p className="main-article__text">{description}</p> 
      <span className="article-source main-article__caption">{source}</span> 
    </div> 
  </article> 
);

const SmallArticle = ({ title, source, date }) => (
  <article className="small-article"> 
    <h2 className="small-article__title">{title}</h2> 
    <span className="article-source">{source}</span> 
    <span className="article-date"> 
      {new Date(date).toLocaleDateString('ru-RU', { month: 'long', day: 'numeric' })} 
    </span> 
  </article> 
);

const App = () => { 
  const [category, setCategory] = React.useState('index'); 

  const onNavClick = (e) => { 
    e.preventDefault(); 
    setCategory(e.currentTarget.dataset.href); 
  };

  // Фильтруем новости локально вместо useEffect
  const filteredItems = React.useMemo(() => {
    const currentCategoryId = categoryIds[category];
    // Если "Главная" (id: 0), показываем всё, иначе фильтруем по category_id
    if (currentCategoryId === 0) {
      return Data.items;
    }
    return Data.items.filter(item => item.category_id === currentCategoryId);
  }, [category]);

  return ( 
    <React.Fragment> 
      <header className="header"> 
        <div className="container"> 
          <Navigation onNavClick={onNavClick} currentCategory={category} className="header__navigation" /> 
        </div> 
      </header> 

      <main> 
        <section className="articles"> 
          <div className="container grid"> 
            <section className="articles__big-column"> 
              {filteredItems.slice(0, 3).map((item) => ( 
                <MainArticle 
                  key={item.id} // Лучше использовать id вместо title
                  title={item.title} 
                  description={item.description} 
                  image={item.image} 
                  category={Data.categories.find(({id}) => item.category_id === id)?.name || 'News'} 
                  source={Data.sources.find(({id}) => item.source_id === id)?.name || 'Source'} 
                /> 
              ))} 
            </section> 
            <section className="articles__small-column"> 
              {filteredItems.slice(3, 7).map((item) => ( 
                <SmallArticle 
                  key={item.id} 
                  title={item.title} 
                  source={Data.sources.find(({id}) => item.source_id === id)?.name || 'Source'} 
                  date={item.date} 
                /> 
              ))} 
            </section> 
          </div> 
        </section> 
      </main> 

      <footer className="footer"> 
        <div className="container"> 
          <Navigation2 onNavClick={onNavClick} currentCategory={category} className="footer__navigation" /> 
          <div className="footer__bottom"> 
            <p className="footer__text">Сделано на Frontend курсе в <a className="footer__link" href="https://karpov.courses/frontend" target="_blank">Karpov.Courses</a></p> 
            <p className="footer__text footer__text--gray">© 2021</p> 
          </div> 
        </div> 
      </footer> 
    </React.Fragment> 
  );
};

ReactDOM.render(<App />, document.getElementById('root'));